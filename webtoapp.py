#!/usr/bin/env python3
"""
WebToApp - turn any website into a lightweight Windows desktop app.

A Pake-style tool: enter a URL, pick a name/icon/options, click Build and get a
standalone .exe that opens the site in its own native window (Microsoft Edge
WebView2 under the hood, via pywebview).

Run:  python webtoapp.py
"""
import hashlib
import io
import json
import os
import queue
import re
import shutil
import subprocess
import sys
import tempfile
import threading
import tkinter as tk
import urllib.request
from tkinter import filedialog, messagebox, ttk
from tkinter.scrolledtext import ScrolledText
from urllib.parse import urlparse

APP_TITLE = "WebToApp"
HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_OUT = os.path.join(HERE, "output")

REQUIRED = [("webview", "pywebview"), ("PyInstaller", "pyinstaller"), ("PIL", "pillow")]

# (key, label, default)
OPTIONS = [
    ("resizable", "Resizable window", True),
    ("maximized", "Start maximized", False),
    ("fullscreen", "Start fullscreen", False),
    ("always_on_top", "Always on top", False),
    ("frameless", "Frameless (no title bar)", False),
    ("single_instance", "Allow only one instance", True),
    ("external_links", "Open other-domain links in default browser", False),
    ("dark_mode", "Force dark mode (experimental)", False),
    ("devtools", "Enable DevTools (F12 / right-click > Inspect)", False),
]

# --------------------------------------------------------------------------- #
# Runtime template: this becomes the generated app's entry point.
# __CONFIG__ is replaced with a JSON string literal.
# --------------------------------------------------------------------------- #
RUNTIME_TEMPLATE = r'''"""Generated by WebToApp."""
import ctypes
import hashlib
import json
import os
import sys
import webbrowser
from urllib.parse import urlparse

import webview

CONFIG = json.loads(__CONFIG__)

LINK_JS = """
(function () {
  if (window.__w2a) return; window.__w2a = true;
  var HOME = __HOME__, EXTERNAL = __EXTERNAL__;
  document.addEventListener("click", function (e) {
    var a = e.target && e.target.closest ? e.target.closest("a[href]") : null;
    if (!a) return;
    var u; try { u = new URL(a.href, location.href); } catch (_) { return; }
    if (u.protocol !== "http:" && u.protocol !== "https:") return;
    var external = HOME && !u.hostname.endsWith(HOME);
    if (external && EXTERNAL && window.pywebview && window.pywebview.api) {
      e.preventDefault(); window.pywebview.api.open_external(u.href);
    } else if (a.target === "_blank") {
      e.preventDefault(); location.href = u.href;
    }
  }, true);
  window.open = function (url) { if (url) location.href = url; return null; };
})();
"""


def data_dir():
    base = os.environ.get("LOCALAPPDATA") or os.path.expanduser("~")
    path = os.path.join(base, "WebToApp", CONFIG["safe_name"])
    os.makedirs(path, exist_ok=True)
    return path


def ensure_single_instance():
    if not CONFIG.get("single_instance"):
        return None
    key = hashlib.md5(CONFIG["url"].encode("utf-8")).hexdigest()
    handle = ctypes.windll.kernel32.CreateMutexW(None, False, "Local\\WebToApp_" + key)
    if ctypes.windll.kernel32.GetLastError() == 183:  # ERROR_ALREADY_EXISTS
        sys.exit(0)
    return handle


def load_state():
    try:
        with open(os.path.join(data_dir(), "window.json"), "r", encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return {}


def save_state(window):
    if CONFIG.get("maximized") or CONFIG.get("fullscreen"):
        return
    try:
        with open(os.path.join(data_dir(), "window.json"), "w", encoding="utf-8") as f:
            json.dump({"width": window.width, "height": window.height}, f)
    except Exception:
        pass


def build_js():
    host = urlparse(CONFIG["url"]).hostname or ""
    home = ".".join(host.split(".")[-2:])
    parts = []

    css = (CONFIG.get("custom_css") or "").strip()
    if CONFIG.get("dark_mode"):
        css += (
            "\nhtml{filter:invert(1) hue-rotate(180deg)!important;background:#fff}"
            "\nimg,picture,video,canvas{filter:invert(1) hue-rotate(180deg)!important}"
        )
    if css:
        parts.append(
            "(function(){var s=document.createElement('style');s.textContent=%s;"
            "(document.head||document.documentElement).appendChild(s);})();" % json.dumps(css)
        )

    zoom = int(CONFIG.get("zoom") or 100)
    if zoom != 100:
        parts.append("document.documentElement.style.zoom='%d%%';" % zoom)

    parts.append(
        LINK_JS.replace("__HOME__", json.dumps(home)).replace(
            "__EXTERNAL__", "true" if CONFIG.get("external_links") else "false"
        )
    )

    user_js = (CONFIG.get("custom_js") or "").strip()
    if user_js:
        parts.append("try{\n" + user_js + "\n}catch(e){console.error(e);}")
    return "\n".join(parts)


class Api:
    def open_external(self, url):
        if isinstance(url, str) and url.startswith(("http://", "https://")):
            webbrowser.open(url)


def main():
    _mutex = ensure_single_instance()  # keep handle alive for process lifetime
    state = load_state()
    width = int(state.get("width") or CONFIG["width"])
    height = int(state.get("height") or CONFIG["height"])

    window = webview.create_window(
        CONFIG["title"],
        CONFIG["url"],
        js_api=Api(),
        width=width,
        height=height,
        min_size=(360, 280),
        resizable=bool(CONFIG["resizable"]),
        fullscreen=bool(CONFIG["fullscreen"]),
        on_top=bool(CONFIG["always_on_top"]),
        frameless=bool(CONFIG["frameless"]),
        easy_drag=bool(CONFIG["frameless"]),
        maximized=bool(CONFIG["maximized"]),
        text_select=True,
    )

    injection = build_js()

    def on_loaded():
        try:
            window.evaluate_js(injection)
        except Exception:
            pass

    window.events.loaded += on_loaded
    window.events.closing += lambda: save_state(window)

    try:
        webview.settings["ALLOW_DOWNLOADS"] = True
        webview.settings["OPEN_DEVTOOLS_IN_DEBUG"] = False
    except Exception:
        pass

    kwargs = dict(
        storage_path=data_dir(),   # persist cookies / logins
        private_mode=False,
        debug=bool(CONFIG["devtools"]),
    )
    if CONFIG.get("user_agent"):
        kwargs["user_agent"] = CONFIG["user_agent"]
    webview.start(**kwargs)


if __name__ == "__main__":
    main()
'''


