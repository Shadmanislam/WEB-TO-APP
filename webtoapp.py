def normalize_url(u):
    u = (u or "").strip()
    if not u:
        return ""
    if not re.match(r"^[a-zA-Z][a-zA-Z0-9+.-]*://", u):
        u = "https://" + u
    return u


def safe_filename(name):
    s = re.sub(r"[^\w\- ]", "", name or "", flags=re.UNICODE).strip()
    return s or "WebApp"


def guess_name(url):
    host = urlparse(normalize_url(url)).hostname or ""
    host = re.sub(r"^www\.", "", host)
    label = host.split(".")[0] if host else ""
    return label.capitalize() if label else ""


def run_cmd(cmd, log, cwd=None):
    flags = getattr(subprocess, "CREATE_NO_WINDOW", 0)
    proc = subprocess.Popen(
        cmd,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        encoding="utf-8",
        errors="replace",
        cwd=cwd,
        creationflags=flags,
    )
    for line in proc.stdout:
        line = line.rstrip()
        if line:
            log(line)
    code = proc.wait()
    if code != 0:
        raise RuntimeError("Command failed (exit code %d). See the log above." % code)


def ensure_deps(log):
    import importlib.util

    missing = [pkg for mod, pkg in REQUIRED if importlib.util.find_spec(mod) is None]
    if missing:
        log("Installing required packages: " + ", ".join(missing))
        run_cmd([sys.executable, "-m", "pip", "install", *missing], log)


def fetch_bytes(url, timeout=8):
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 WebToApp"})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return r.read()


def letter_icon(name):
    from PIL import Image, ImageDraw, ImageFont

    size = 256
    h = int(hashlib.md5(name.encode("utf-8")).hexdigest()[:6], 16)
    color = (60 + h % 140, 60 + (h >> 8) % 140, 60 + (h >> 16) % 140, 255)
    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    d.rounded_rectangle((8, 8, size - 8, size - 8), radius=56, fill=color)
    letter = (name.strip()[:1] or "W").upper()
    font = None
    for fname in ("arialbd.ttf", "arial.ttf", "DejaVuSans-Bold.ttf"):
        try:
            font = ImageFont.truetype(fname, 150)
            break
        except Exception:
            continue
    if font is None:
        font = ImageFont.load_default()
    box = d.textbbox((0, 0), letter, font=font)
    tw, th = box[2] - box[0], box[3] - box[1]
    d.text(
        ((size - tw) / 2 - box[0], (size - th) / 2 - box[1]),
        letter,
        font=font,
        fill=(255, 255, 255, 255),
    )
    return img


def make_icon(icon_src, url, name, ico_path, log):
    """Create a multi-size .ico from a file, the site's favicon, or a letter tile."""
    from PIL import Image

    img = None
    if icon_src and os.path.isfile(icon_src):
        log("Using icon: " + icon_src)
        img = Image.open(icon_src)
        img.load()
    else:
        p = urlparse(url)
        candidates = [
            "https://www.google.com/s2/favicons?domain=%s&sz=256" % p.hostname,
            "%s://%s/favicon.ico" % (p.scheme, p.netloc),
        ]
        for cand in candidates:
            try:
                log("Fetching favicon: " + cand)
                img = Image.open(io.BytesIO(fetch_bytes(cand)))
                img.load()
                break
            except Exception:
                img = None
        if img is None:
            log("No favicon found - generating a letter icon.")
            img = letter_icon(name)

    img = img.convert("RGBA")
    side = max(img.size)
    canvas = Image.new("RGBA", (side, side), (0, 0, 0, 0))
    canvas.paste(img, ((side - img.width) // 2, (side - img.height) // 2))
    if side != 256:
        canvas = canvas.resize((256, 256), Image.LANCZOS)
    canvas.save(
        ico_path,
        format="ICO",
        sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)],
    )


def build_app(cfg, icon_src, out_dir, onefile, log):
    safe = cfg["safe_name"]
    work = tempfile.mkdtemp(prefix="webtoapp_")
    try:
        script = os.path.join(work, "app_main.py")
        with open(script, "w", encoding="utf-8") as f:
            f.write(RUNTIME_TEMPLATE.replace("__CONFIG__", json.dumps(json.dumps(cfg))))

        ico = os.path.join(work, "icon.ico")
        make_icon(icon_src, cfg["url"], cfg["title"], ico, log)

        os.makedirs(out_dir, exist_ok=True)
        cmd = [
            sys.executable, "-m", "PyInstaller",
            "--noconfirm", "--clean", "--noconsole",
            "--onefile" if onefile else "--onedir",
            "--name", safe,
            "--icon", ico,
            "--distpath", out_dir,
            "--workpath", os.path.join(work, "build"),
            "--specpath", work,
            "--collect-all", "webview",
            "--collect-all", "clr_loader",
            "--collect-all", "pythonnet",
            script,
        ]
        log("Packaging with PyInstaller (this takes a minute)...")
        run_cmd(cmd, log, cwd=work)

        exe = os.path.join(out_dir, safe + ".exe") if onefile else os.path.join(out_dir, safe, safe + ".exe")
        if not os.path.isfile(exe):
            # non-Windows or unexpected layout: report whatever was produced
            exe = os.path.join(out_dir, safe)
        return exe
    finally:
        shutil.rmtree(work, ignore_errors=True)


